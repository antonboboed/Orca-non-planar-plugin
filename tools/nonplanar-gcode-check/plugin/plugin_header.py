"""Nonplanar G-code Check: a G-code verifier for OrcaSlicer 2.5.2.

STATUS
    Experimental. Not validated on a real P1S export. Not a safety certificate.
    The collision rule is stricter than the reference's final check for contacts with the
    bead being printed (see docs/test-results.md). A clean report is not a guarantee.

WHAT IT DOES
    Runs at the G-code export/post-process step (Step.psGCodePostProcess) and reads the
    exported file. It never edits the file. It checks:
      * SLOPE: extrusion moves steeper than max_angle_deg (default 12). Travel only when descending.
      * Z_NEGATIVE: extrusion below the bed. Calibration touches below Z=0 without extrusion are allowed.
      * COLLISION: the nozzle tip and cone (A1 mini model from the nonplanar reference) against
        material already deposited, with bead half width added as margin.
      * Arcs (G2/G3) are split into chords and checked like G1.
    On errors it returns FatalError, so the export stops and the file is not sent to the printer.
    Warnings and the full report are written to the OrcaSlicer log.

WHAT IT DOES NOT DO
    * It does not change the toolpath: OrcaSlicer 2.5.2 plugins cannot set Z of extrusion points.
    * It does not model the heater block above 2.5 mm (reported as UNCHECKED_HIGH, not passed).
    * It does not know the real hotend of your printer. The model is for A1 mini, not P1S.
    * It does not plan print order.

SETTINGS (JSON in the plugin config)
    max_angle_deg  float  default 12.0   maximum slope of extrusion moves, degrees
    fail_on_error  bool   default true   stop the export on errors; false = log only

INSTALL (not yet verified on Windows Server 2019 with P1S)
    The file name must end with a supported OS and arch target before .py, for example
    orca_nonplanar_gcode_check_plugin_win_x86_64.py. A name without the target is rejected.
    Plugins window in OrcaSlicer, install a local package from this file, enable it.
    The exact button name can differ between builds.

CHANGELOG
    0.1  first draft: slope, Z, collision (tip + cone), arcs as chords, calibration-aware Z check.

Source of truth for the checker is gcode_check.py; this file is generated by build_plugin.py.
See tools/nonplanar-gcode-check/README.md and docs/test-results.md.
"""
import json

import orca

_DEFAULTS = {
    "max_angle_deg": 12.0,
    "fail_on_error": True,
}


def _config(self):
    try:
        cfg = json.loads(self.get_config())
    except (AttributeError, TypeError, ValueError):
        cfg = {}
    out = dict(_DEFAULTS)
    out.update({k: v for k, v in cfg.items() if k in _DEFAULTS})
    return out


class NonplanarGCodeCheck(orca.slicing.SlicingPipelineCapabilityBase):
    def get_name(self):
        return "Nonplanar G-code Check"

    def get_default_config(self):
        return dict(_DEFAULTS)

    def execute(self, ctx):
        if ctx.step != orca.slicing.Step.psGCodePostProcess:
            return orca.ExecutionResult.success()
        if not ctx.gcode_path:
            return orca.ExecutionResult.success("Nonplanar G-code Check: no gcode_path, nothing to do")

        cfg = _config(self)
        checker = Checker(max_angle_deg=float(cfg["max_angle_deg"]))
        with open(ctx.gcode_path, "r", encoding="utf-8", errors="replace") as f:
            report = checker.run(f)
        text = format_report(ctx.gcode_path, report, float(cfg["max_angle_deg"]))
        for line in text.splitlines():
            print(line)

        if report.errors and cfg["fail_on_error"]:
            first = [i for i in report.issues if i.level == "error"][:3]
            detail = "; ".join(f"{i.code} line {i.line}: {i.message}" for i in first)
            return orca.ExecutionResult.failure(
                orca.PluginResult.FatalError,
                f"Nonplanar G-code Check found {report.errors} error(s), export stopped. {detail}")

        return orca.ExecutionResult.success(
            f"Nonplanar G-code Check: {report.errors} error(s), {len(report.issues) - report.errors} other issue(s)")


@orca.plugin
class NonplanarGCodeCheckPackage(orca.base):
    def register_capabilities(self):
        orca.register_capability(NonplanarGCodeCheck)
